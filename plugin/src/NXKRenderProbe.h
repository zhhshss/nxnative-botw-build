typedef struct {
    uintptr_t base;
    bool ready;
    double time;
    uint64_t presents,passes,draws,library_ns,pipeline_ns;
} NXKRenderProbe;
typedef struct {
    bool valid,gpu_valid;
    double fps,mean_frame_ms,passes_per_frame,draws_per_frame,compile_ms,gpu_span_ms;
} NXKRenderSample;
static inline bool nxk_probe_init(NXKRenderProbe *p,uintptr_t base) {
    memset(p,0,sizeof(*p));
    for (unsigned i=0;i<sizeof(nxk_probe_fingerprints)/sizeof(nxk_probe_fingerprints[0]);i++) {
        uint8_t hash[32];
        CC_SHA256((const void *)(base+nxk_probe_fingerprints[i].offset),nxk_probe_fingerprints[i].size,hash);
        if (memcmp(hash,nxk_probe_fingerprints[i].hash,32)) return false;
    }
    p->base=base; p->ready=true; return true;
}
static inline NXKRenderSample nxk_probe_sample(NXKRenderProbe *p,double now) {
    NXKRenderSample out={0};
    if (!p->ready) return out;
    uintptr_t base=p->base;
    uint64_t presents=((uint64_t(*)(void))(base+nxk_probe_fingerprints[4].offset))();
    uint64_t passes=0,draws=0,library_ns=0,pipeline_ns=0;
    ((void(*)(uint64_t *,uint64_t *))(base+nxk_probe_fingerprints[2].offset))(&passes,&draws);
    ((void(*)(uint64_t *,uint64_t *))(base+nxk_probe_fingerprints[3].offset))(&library_ns,&pipeline_ns);
    if (p->time && now>p->time && presents>=p->presents && passes>=p->passes && draws>=p->draws && library_ns>=p->library_ns && pipeline_ns>=p->pipeline_ns) {
        uint64_t n=presents-p->presents;
        double dt=now-p->time;
        out.valid=true; out.fps=n/dt;
        out.mean_frame_ms=n?dt*1000/n:0;
        out.passes_per_frame=n?(double)(passes-p->passes)/n:0;
        out.draws_per_frame=n?(double)(draws-p->draws)/n:0;
        out.compile_ms=((library_ns-p->library_ns)+(pipeline_ns-p->pipeline_ns))/1e6;
    }
    p->time=now; p->presents=presents; p->passes=passes; p->draws=draws;
    p->library_ns=library_ns; p->pipeline_ns=pipeline_ns;
    uint64_t frame=atomic_load((_Atomic uint64_t *)(base+NXK_RENDER_FRAME_OFFSET));
    for (unsigned i=1;i<=8 && frame>=i;i++) {
        uint64_t t0=0,t1=0;
        if (((int(*)(uint64_t,uint64_t *,uint64_t *))(base+nxk_probe_fingerprints[1].offset))(frame-i,&t0,&t1) && t1>=t0 && t1) {
            out.gpu_valid=true; out.gpu_span_ms=(t1-t0)/1e6; break;
        }
    }
    return out;
}
